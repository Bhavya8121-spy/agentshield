from __future__ import annotations

import os
import time
from pathlib import Path
from typing import List

from ..models import CleanableItem, Safety
from ..utils import disk_usage
from .base import Cleaner

STALE_DAYS = 90
MAX_DEPTH = 6
MAX_RESULTS = 25
_SKIP_DIRS = {"Library", "Applications"}


def _mtime(path: Path) -> float:
    try:
        return os.stat(path).st_mtime
    except OSError:
        return 0.0


class NodeModulesCleaner(Cleaner):
    """Finds node_modules in projects untouched for 90+ days. Report only."""

    name = "node_modules"

    def scan(self) -> List[CleanableItem]:
        cutoff = time.time() - STALE_DAYS * 86400
        items: List[CleanableItem] = []

        for dirpath, dirnames, _ in os.walk(self.home, topdown=True):
            project = Path(dirpath)
            depth = len(project.relative_to(self.home).parts)

            if "node_modules" in dirnames:
                dirnames.remove("node_modules")  # never descend into it
                modules = project / "node_modules"
                last_touched = max(_mtime(project / "package.json"), _mtime(modules))
                if not modules.is_symlink() and last_touched < cutoff:
                    size = disk_usage(modules)
                    if size > 0:
                        items.append(
                            CleanableItem(
                                category=self.name,
                                label=f"~/{modules.relative_to(self.home)}",
                                size=size,
                                safety=Safety.REVIEW,
                                path=modules,
                                report_only=True,
                                note=f"Project untouched for {STALE_DAYS}+ days; `npm ci` restores it",
                            )
                        )

            if depth >= MAX_DEPTH:
                dirnames[:] = []
            else:
                dirnames[:] = [
                    d
                    for d in dirnames
                    if d not in _SKIP_DIRS and not d.startswith(".")
                ]

        items.sort(key=lambda i: -i.size)
        return items[:MAX_RESULTS]
